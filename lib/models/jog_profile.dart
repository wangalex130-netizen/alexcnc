// 点动进给档位表 —— 单一事实来源（三方共识 A1-2，2026-09-11）。
//
// 背景：App 此前点动帧**不带 feed**，固件按缺省 F600 执行
// （`cnc_net.c:1432` 单轴分支 / `:1443` 多轴分支）。而旧连发间隔是 **180ms**，
// 10mm 档在 F600 下需 1000ms 才走完 —— 帧的到达速度是消耗速度的 5.5 倍，
// GRBL 运动队列必然堆积，松手后仍继续走。
//
// 按步长匹配进给，使「走完一步」与「下一帧到达」量级相当：
//
//   | 档位   | 进给  | 走完一步 | 说明             |
//   |--------|-------|----------|------------------|
//   | 0.1 mm | F300  | 20 ms    | 精细对刀，慢才准 |
//   | 1 mm   | F600  | 100 ms   | 与固件缺省一致   |
//   | 10 mm  | F1500 | 400 ms   | 快速粗调         |
//
// ⚠️ 这是**软件侧减害**，不改变「长按只发一次」（共识 S1）的结论 —— 两者叠加才完整。

/// 返回 [stepMm] 档位对应的进给（mm/min）。负值按绝对值处理（方向不影响速度）。
double jogFeedForStep(double stepMm) {
  final mm = stepMm.abs();
  if (mm <= 0.1) return 300;
  if (mm <= 1.0) return 600;
  return 1500;
}
